const ANCHOR_AD = Date.UTC(1944, 0, 1), ANCHOR_BS = [2000, 9, 17]; // 1944-01-01 AD = 2000-09-17 BS (same anchor as the add-in)
const DAY = 864e5, p2 = n => String(n).padStart(2, '0');

const bsDays = (y, m) => (BS[y - START] || [])[m - 1] || 0;

// BS day number counted from the anchor
const bsOrd = (y, m, d) => { let n = 0; for (let i = ANCHOR_BS[0]; i < y; i++) n += BS[i - START].reduce((a, b) => a + b, 0); for (let i = 1; i < m; i++) n += bsDays(y, i); return n + d - 1; };

const ANCHOR_ORD = bsOrd(...ANCHOR_BS);

export const bsValid = (y, m, d) => y >= START && y < START + BS.length && m >= 1 && m <= 12 && d >= 1 && d <= bsDays(y, m);

// "2026-11-03" (or 2026/11/03) -> "2083-07-17", or '' if not a valid date in range
export function ad2bs(ad) {
  const m = /^(\d{4})[-\/.](\d{1,2})[-\/.](\d{1,2})$/.exec(String(ad || '').trim()); if (!m) return '';
  const t = Date.UTC(+m[1], +m[2] - 1, +m[3]); if (isNaN(t) || new Date(t).getUTCMonth() != +m[2] - 1) return '';
  let n = Math.round((t - ANCHOR_AD) / DAY) + ANCHOR_ORD; if (n < 0) return '';
  let y = START; for (; y < START + BS.length; y++) { const L = BS[y - START].reduce((a, b) => a + b, 0); if (n < L) break; n -= L; }
  if (y >= START + BS.length) return '';
  let mo = 1; while (n >= bsDays(y, mo)) { n -= bsDays(y, mo); mo++; }
  return y + '-' + p2(mo) + '-' + p2(n + 1);
}

// "2083-07-17" (or 2083/7/17) -> "2026-11-03", or '' if invalid
export function bs2ad(bs) {
  const m = /^(\d{4})[-\/.](\d{1,2})[-\/.](\d{1,2})$/.exec(String(bs || '').trim()); if (!m) return '';
  const y = +m[1], mo = +m[2], d = +m[3]; if (!bsValid(y, mo, d)) return '';
  const t = new Date(ANCHOR_AD + (bsOrd(y, mo, d) - ANCHOR_ORD) * DAY); return t.getUTCFullYear() + '-' + p2(t.getUTCMonth() + 1) + '-' + p2(t.getUTCDate());
}

// Normalise whatever was typed into a BS date as yyyy-mm-dd (2083/7/5 -> 2083-07-05), or '' if it is not a real BS date
export const bsNorm = s => { const m = /^(\d{4})[-\/.](\d{1,2})[-\/.](\d{1,2})$/.exec(String(s || '').trim()); return m && bsValid(+m[1], +m[2], +m[3]) ? m[1] + '-' + p2(+m[2]) + '-' + p2(+m[3]) : ''; };

// A single field that may hold either kind: year >= 2060 is read as BS, otherwise AD. Returns {ad, bs} or null.
export function either(s) {
  const m = /^(\d{4})/.exec(String(s || '').trim()); if (!m) return null;
  if (+m[1] >= 2060) { const ad = bs2ad(s); return ad ? { ad, bs: bsNorm(s) } : null; }
  const bs = ad2bs(s); return bs ? { ad: String(s).trim().replace(/[\/.]/g, '-').replace(/-(\d)(?=-|$)/g, '-0$1'), bs } : null;
}
